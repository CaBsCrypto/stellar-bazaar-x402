import assert from 'node:assert/strict';
import {createPrivateReadQueue} from '../lib/private-read-queue.ts';
const queue=createPrivateReadQueue(),calls=[];
let finishA,finishB;
const active=queue('owner-a',undefined,()=>{calls.push('active-a');return new Promise(resolve=>{finishA=resolve;});});
const controller=new AbortController();
const cancelled=queue('owner-a',controller.signal,async()=>{calls.push('cancelled-a');});
const cancelledResult=assert.rejects(cancelled,{name:'AbortError'});
const following=queue('owner-a',undefined,async()=>{calls.push('following-a');return 'next';});
const other=queue('owner-b',undefined,()=>{calls.push('active-b');return new Promise(resolve=>{finishB=resolve;});});
controller.abort();await cancelledResult;
assert.deepEqual(calls,['active-a','active-b'],'Other owners are independent; cancelled pending read makes no request');
finishB('other');assert.equal(await other,'other');
assert.deepEqual(calls,['active-a','active-b'],'Aborting a queued turn cannot detach the active predecessor');
finishA('first');assert.equal(await active,'first');assert.equal(await following,'next');
assert.deepEqual(calls,['active-a','active-b','following-a']);
let failures=0;
await assert.rejects(queue('owner-a',undefined,async()=>{failures++;throw Error('transport-failed');}),/transport-failed/);
assert.equal(failures,1,'A failed transport is never retried');
assert.equal(await queue('owner-a',undefined,async()=>42),42,'A failed read releases the owner turn');
const alreadyAborted=new AbortController();alreadyAborted.abort();
await assert.rejects(queue('owner-a',alreadyAborted.signal,async()=>{throw Error('must-not-run');}),{name:'AbortError'});
console.log('PASS private read queue: same-owner panels serialize, independent owners progress, queued abort issues no request and retains active predecessor, failure releases without retry. No external requests.');
