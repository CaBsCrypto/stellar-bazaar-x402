const reverse = new Map(Object.entries(uiCopy).map(([es, en]) => [en, es]));
export function translateUi(language: UiLanguage, source: string, values: readonly unknown[] = []): string {
  const key = source.trim().replace(/\s+/g, ' ');
  const translated = language === 'en' ? (uiCopy[key] ?? key) : (reverse.get(key) ?? key);
  return translated.replace(/\{(\d+)\}/g, (placeholder, index: string) =>
    Number(index) < values.length ? String(values[Number(index)]) : placeholder);
}

